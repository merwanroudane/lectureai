ui.section("لماذا لا نحلّ المسألة مباشرةً؟", "Why not just solve it?")

st.markdown(
    r"""
في الانحدار الخطّي بالمربّعات الصغرى، يوجد **حلّ مغلق** يُحسب مرّة واحدة:

$$
\hat{\beta} = (X^\top X)^{-1} X^\top y
$$

فلماذا نحتاج التدريب التكراري أصلًا؟ لأربعة أسباب:

1. **لا حلّ مغلقًا لمعظم النماذج.** دالّة الخسارة في الشبكات العصبية (أو الانحدار اللوجستي)
   **غير محدّبة** أو غير قابلة للحلّ جبريًّا.
2. **الكلفة الحسابية.** قلب مصفوفة بأبعاد `p × p` يكلّف `O(p³)`.
   عند `p = 100,000` معامل، هذا مستحيل عمليًّا.
3. **الذاكرة.** لا يمكن تحميل ملايين الأمثلة دفعةً واحدة.
4. **الانتظام الضمني.** التوقّف المبكّر والتشويش في الدفعات يعملان **كانتظام**
   يحسّن التعميم — وهو ما لا يعطيه الحلّ المغلق.
"""
)

