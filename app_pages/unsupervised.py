st.markdown(
    """
السؤال الأصعب في التجميع، ولا جواب رياضيًّا قاطعًا عليه. الأدوات المتاحة:

1. **طريقة المرفق** (`elbow`): ارسم التباين داخل العناقيد مقابل `k`، وابحث عن انكسار المنحنى.
   *العيب:* المرفق غالبًا غير واضح، وتفسيره ذاتيّ.
2. **معامل الظلّ** (`silhouette`): اختر `k` الذي يعظّمه.
   *العيب:* منحاز نحو العناقيد الكروية.
3. **إحصاءة الفجوة** (`gap statistic`): قارن بمرجع عشوائي. أمتن إحصائيًّا، وأبطأ.
4. **BIC / AIC** مع نموذج الخلائط الغاوسية: معيار قائم على الإمكان، يعاقب التعقيد.
5. **القيد الميداني:** أحيانًا `k` محدّد من خارج البيانات —
   «نريد أربع شرائح تسويقية لأنّ لدينا أربعة فرق».

> **قاعدة:** إن تغيّر تفسيرك للنتائج جذريًّا بتغيّر `k` من 4 إلى 5،
> فالبنية التي وجدتها **هشّة**، ولا ينبغي أن تُبنى عليها قرارات.
"""
)

