@st.cache_data(ttl=600, max_entries=48)
def _sampling(n: int, reps: int) -> tuple[pd.DataFrame, pd.DataFrame, float]:
    rng = np.random.default_rng(42)
    pop = rng.exponential(scale=2.0, size=200_000)
    means = rng.exponential(scale=2.0, size=(reps, n)).mean(axis=1)
    return (
        pd.DataFrame({"القيمة": pop[:8000]}),
        pd.DataFrame({"المتوسّط": means}),
        float(means.std()),
    )


pop_df, mean_df, se = _sampling(n_size, n_rep)

g1, g2 = st.columns(2)
with g1:
    st.caption("توزيع المجتمع الأصلي · the (skewed) population")
    st.altair_chart(
        alt.Chart(pop_df).mark_bar(color="#EBA85A", opacity=0.85).encode(
            x=alt.X("القيمة:Q", bin=alt.Bin(maxbins=60), title="x"),
            y=alt.Y("count()", title="التكرار"),
        ).properties(height=250),
        width="stretch",
    )
with g2:
    st.caption("توزيع متوسّطات العيّنات · the sampling distribution of x̄")
    st.altair_chart(
        alt.Chart(mean_df).mark_bar(color="#5A6AE0", opacity=0.9).encode(
            x=alt.X("المتوسّط:Q", bin=alt.Bin(maxbins=60), title="x̄",
                    scale=alt.Scale(domain=[0, 6])),
            y=alt.Y("count()", title="التكرار"),
        ).properties(height=250),
        width="stretch",
    )

k1, k2, k3 = st.columns(3)
