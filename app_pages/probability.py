ui.section("مبرهنة بايز: آلة تحديث الاعتقاد", "Bayes' theorem")

st.markdown(
    r"""
$$ \underbrace{P(H \mid D)}_{\text{البَعْدي}} \;=\;
\frac{\overbrace{P(D \mid H)}^{\text{الإمكان}} \cdot \overbrace{P(H)}^{\text{القَبْلي}}}
{\underbrace{P(D)}_{\text{الدليل}}} $$

| الرمز | الاسم | المعنى |
|---|---|---|
| $P(H)$ | القَبْلي · `prior` | اعتقادي **قبل** رؤية الدليل |
| $P(D \mid H)$ | الإمكان · `likelihood` | ما مدى توقّع هذا الدليل لو صحّت الفرضية؟ |
| $P(H \mid D)$ | البَعْدي · `posterior` | اعتقادي **بعد** رؤية الدليل |
| $P(D)$ | الدليل · `evidence` | ثابت تطبيع يضمن أنّ المجموع = 1 |

هذه ليست صيغة تقنية؛ إنّها **وصفٌ لكيفية تعلّم العقل العقلاني من التجربة**:
ابدأ باعتقادٍ ما، انظر إلى الدليل، حدِّث بنسبة قوّة الدليل.
"""
)

