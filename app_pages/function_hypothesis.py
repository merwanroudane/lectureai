@st.cache_data(ttl=600, max_entries=64)
def _poly_fit(degree: int, n: int, sigma: float) -> tuple[pd.DataFrame, pd.DataFrame]:
    rng = np.random.default_rng(7)
    x = np.sort(rng.uniform(0, 1, n))
    y_true = np.sin(2 * np.pi * x)
    y = y_true + rng.normal(0, sigma, n)
    grid = np.linspace(0, 1, 220)
    coef = np.polyfit(x, y, degree)
    fit = np.polyval(coef, grid)
    lo, hi = y.min() - 1.2, y.max() + 1.2
    fit = np.clip(fit, lo, hi)
    frames = [
        pd.DataFrame({"x": grid, "y": np.sin(2 * np.pi * grid), "نوع": "الدالّة الحقيقية f"}),
        pd.DataFrame({"x": grid, "y": fit, "نوع": "التقدير f̂"}),
    ]
    pts = pd.DataFrame({"x": x, "y": y, "نوع": "نقاط التدريب"})
    return pd.concat(frames, ignore_index=True), pts


