@st.cache_data(ttl=600, max_entries=64)
def _bv_curve(n: int, s: float, dmax: int) -> pd.DataFrame:
    rng = np.random.default_rng(13)
    x_tr = np.sort(rng.uniform(0, 1, n))
    y_tr = np.sin(2 * np.pi * x_tr) + rng.normal(0, s, n)
    x_te = np.sort(rng.uniform(0, 1, 400))
    y_te = np.sin(2 * np.pi * x_te) + rng.normal(0, s, 400)
    rows = []
    for d in range(1, dmax + 1):
        try:
            c = np.polyfit(x_tr, y_tr, d)
        except Exception:
            continue
        tr = float(np.mean((np.polyval(c, x_tr) - y_tr) ** 2))
        te = float(np.mean((np.clip(np.polyval(c, x_te), -8, 8) - y_te) ** 2))
        rows.append({"الدرجة": d, "الخطأ": tr, "المجموعة": "التدريب"})
        rows.append({"الدرجة": d, "الخطأ": min(te, 4.0), "المجموعة": "الاختبار"})
    return pd.DataFrame(rows)


